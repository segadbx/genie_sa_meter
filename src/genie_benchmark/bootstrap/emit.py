"""Emit a ready-to-run ``config.yaml`` and ``questions.json`` from provisioning results.

The emitted config contains only non-secret identifiers (never a token/profile secret) and
is validated with the runtime loader's :func:`parse_config` before being written, so a
bootstrap can never produce a config the harness would reject. When a config file already
exists it is *patched* (extra user keys such as ``store_response_text`` are preserved).
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

import yaml

from ..config import parse_config
from .settings import BootstrapSettings

_CONFIG_HEADER = (
    "# Generated by `benchmark bootstrap`. Contains only non-secret identifiers.\n"
    "# Authentication is resolved from the Databricks profile below (no credentials here).\n"
    "# Re-run the bootstrap to refresh, or edit by hand.\n"
)


def build_config_dict(
    settings: BootstrapSettings,
    *,
    workspace_host: str,
    profile: str | None,
    genie_space_id: str,
    experiment_id: str | None,
    supervisor_target: str | None,
    mcp_target: str | None,
) -> dict[str, Any]:
    """Assemble the harness config mapping (non-secret identifiers only).

    Only the variants requested in ``settings.emit.variants`` are included, and each
    enabled variant's target is required to be present — the returned mapping is validated
    with :func:`parse_config`, which enforces exactly those rules.
    """
    variants = list(settings.emit.variants)
    config: dict[str, Any] = {
        "workspace_host": workspace_host,
        "environment": settings.emit.environment,
        "genie_space_id": genie_space_id,
        "variants": variants,
        "questions_file": settings.emit.questions_path,
    }
    if profile:
        config["databricks_profile"] = profile
    if experiment_id:
        config["experiment_id"] = experiment_id
    if "supervisor" in variants and supervisor_target:
        config["supervisor_target"] = supervisor_target
    if "supervisor_mcp" in variants and mcp_target:
        config["mcp_target"] = mcp_target

    # Fail fast if we somehow assembled something the harness would reject.
    parse_config(dict(config))
    return config


def _merge_into_existing(path: Path, new_values: dict[str, Any]) -> dict[str, Any]:
    if not path.exists():
        return dict(new_values)
    try:
        existing = yaml.safe_load(path.read_text(encoding="utf-8"))
    except yaml.YAMLError:
        return dict(new_values)
    if not isinstance(existing, dict):
        return dict(new_values)
    existing.update(new_values)
    return existing


def write_config(path: str | Path, config: dict[str, Any]) -> Path:
    """Write (or patch) the harness config YAML, preserving unrelated existing keys."""
    p = Path(path)
    merged = _merge_into_existing(p, config)
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text(_CONFIG_HEADER + yaml.safe_dump(merged, sort_keys=False), encoding="utf-8")
    return p


def write_questions(path: str | Path, questions: list[dict[str, Any]]) -> Path:
    """Write the benchmark questions JSON file."""
    p = Path(path)
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text(json.dumps(questions, indent=2) + "\n", encoding="utf-8")
    return p
